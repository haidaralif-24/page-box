//! Local storage for pages (SQLite only, no file system operations).

use std::time::{SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};
use tauri::AppHandle;
use uuid::Uuid;

use crate::cleaning;
use crate::db;

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PageMeta {
    pub id: String,
    pub collection_id: Option<i64>,
    pub title: String,
    pub created_at: u64,
    pub updated_at: u64,
}

fn now_millis() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("system clock is before the unix epoch")
        .as_millis() as u64
}

/// Defense in depth: page ids are hyphenated UUID v4 generated by `add_page`.
/// Reject anything else before it touches a path.
fn validate_page_id(id: &str) -> Result<(), String> {
    if id.len() == 36 && id.bytes().all(|b| b.is_ascii_hexdigit() || b == b'-') {
        Ok(())
    } else {
        Err("invalid page id".to_string())
    }
}

pub fn add_page(app: &AppHandle, raw_text: &str, collection_id: Option<i64>) -> Result<PageMeta, String> {
    let cleaned = cleaning::clean_input(raw_text);
    let id = Uuid::new_v4().to_string();
    let now = now_millis();
    
    // Page + initial version + pointer must succeed or fail together, so a
    // failed version insert can never leave an orphan page behind.
    let mut conn = db::get_conn(app)?;
    let tx = conn.transaction().map_err(|e| format!("could not start transaction: {e}"))?;

    tx.execute(
        "INSERT INTO pages (id, collection_id, title, content, created_at, updated_at) VALUES (?1, ?2, ?3, ?4, ?5, ?6)",
        rusqlite::params![id, collection_id, cleaned.title, cleaned.html, now, now],
    ).map_err(|e| format!("could not save page to db: {e}"))?;

    tx.execute(
        "INSERT INTO versions (page_id, content, created_at) VALUES (?1, ?2, ?3)",
        rusqlite::params![id, cleaned.html, now],
    ).map_err(|e| format!("could not save initial version: {e}"))?;

    let version_id = tx.last_insert_rowid();
    tx.execute(
        "UPDATE pages SET current_version_id = ?1 WHERE id = ?2",
        rusqlite::params![version_id, id],
    ).map_err(|e| format!("could not update page version: {e}"))?;

    tx.commit().map_err(|e| format!("could not commit new page: {e}"))?;

    Ok(PageMeta {
        id: id.clone(),
        collection_id,
        title: cleaned.title,
        created_at: now,
        updated_at: now,
    })
}

pub fn list_pages(app: &AppHandle, collection_id: Option<i64>, include_all: bool) -> Result<Vec<PageMeta>, String> {
    let conn = db::get_conn(app)?;
    
    if include_all {
        // "All Pages" view: return every page regardless of collection
        let mut stmt = conn
            .prepare("SELECT id, collection_id, title, created_at, updated_at FROM pages ORDER BY updated_at DESC")
            .map_err(|e| format!("could not prepare list pages: {e}"))?;

        let pages = stmt
            .query_map([], |row| {
                Ok(PageMeta {
                    id: row.get(0)?,
                    collection_id: row.get(1)?,
                    title: row.get(2)?,
                    created_at: row.get(3)?,
                    updated_at: row.get(4)?,
                })
            })
            .map_err(|e| format!("could not query pages: {e}"))?
            .filter_map(Result::ok)
            .collect();

        Ok(pages)
    } else if let Some(cid) = collection_id {
        // Specific collection view
        let mut stmt = conn
            .prepare("SELECT id, collection_id, title, created_at, updated_at FROM pages WHERE collection_id = ?1 ORDER BY updated_at DESC")
            .map_err(|e| format!("could not prepare list pages: {e}"))?;

        let pages = stmt
            .query_map(rusqlite::params![cid], |row| {
                Ok(PageMeta {
                    id: row.get(0)?,
                    collection_id: row.get(1)?,
                    title: row.get(2)?,
                    created_at: row.get(3)?,
                    updated_at: row.get(4)?,
                })
            })
            .map_err(|e| format!("could not query pages: {e}"))?
            .filter_map(Result::ok)
            .collect();

        Ok(pages)
    } else {
        // "Unsorted" view: only pages with no collection
        let mut stmt = conn
            .prepare("SELECT id, collection_id, title, created_at, updated_at FROM pages WHERE collection_id IS NULL ORDER BY updated_at DESC")
            .map_err(|e| format!("could not prepare list pages: {e}"))?;

        let pages = stmt
            .query_map([], |row| {
                Ok(PageMeta {
                    id: row.get(0)?,
                    collection_id: row.get(1)?,
                    title: row.get(2)?,
                    created_at: row.get(3)?,
                    updated_at: row.get(4)?,
                })
            })
            .map_err(|e| format!("could not query pages: {e}"))?
            .filter_map(Result::ok)
            .collect();

        Ok(pages)
    }
}

/// Returns a map of collection_id -> page count, plus an entry for `None` (unsorted)
pub fn count_pages_per_collection(app: &AppHandle) -> Result<Vec<(Option<i64>, i64)>, String> {
    let conn = db::get_conn(app)?;
    let mut stmt = conn
        .prepare("SELECT collection_id, COUNT(*) FROM pages GROUP BY collection_id")
        .map_err(|e| format!("could not prepare page count query: {e}"))?;
    
    let counts = stmt
        .query_map([], |row| {
            Ok((row.get::<_, Option<i64>>(0)?, row.get::<_, i64>(1)?))
        })
        .map_err(|e| format!("could not query page counts: {e}"))?
        .filter_map(Result::ok)
        .collect();
    
    Ok(counts)
}

pub fn delete_page(app: &AppHandle, page_id: &str) -> Result<(), String> {
    validate_page_id(page_id)?;
    db::get_conn(app)?.execute("DELETE FROM pages WHERE id = ?1", rusqlite::params![page_id])
        .map_err(|e| format!("could not delete page from db: {e}"))?;
    Ok(())
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Version {
    pub id: i64,
    pub page_id: String,
    pub created_at: u64,
}

pub fn replace_page(app: &AppHandle, page_id: &str, raw_text: &str) -> Result<PageMeta, String> {
    validate_page_id(page_id)?;
    let cleaned = cleaning::clean_input(raw_text);
    let mut conn = db::get_conn(app)?;
    let tx = conn.transaction().map_err(|e| format!("could not start transaction: {e}"))?;
    let now = now_millis();
    
    // Read existing metadata before updating
    let existing: (Option<i64>, u64) = tx
        .query_row(
            "SELECT collection_id, created_at FROM pages WHERE id = ?1",
            rusqlite::params![page_id],
            |row| Ok((row.get(0)?, row.get(1)?)),
        )
        .map_err(|e| format!("could not read existing page: {e}"))?;

    tx.execute(
        "INSERT INTO versions (page_id, content, created_at) VALUES (?1, ?2, ?3)",
        rusqlite::params![page_id, cleaned.html, now],
    ).map_err(|e| format!("could not save version: {e}"))?;
    let version_id = tx.last_insert_rowid();
    
    tx.execute(
        "UPDATE pages SET current_version_id = ?1, updated_at = ?2, title = ?3, content = ?4 WHERE id = ?5",
        rusqlite::params![version_id, now, cleaned.title, cleaned.html, page_id],
    ).map_err(|e| format!("could not update page: {e}"))?;

    tx.commit().map_err(|e| format!("could not commit replacement: {e}"))?;
    
    Ok(PageMeta {
        id: page_id.to_string(),
        collection_id: existing.0,
        title: cleaned.title,
        created_at: existing.1,
        updated_at: now,
    })
}

pub fn get_page_html(app: &AppHandle, page_id: &str, version_id: Option<i64>) -> Result<String, String> {
    validate_page_id(page_id)?;
    let conn = db::get_conn(app)?;
    
    let content: String = if let Some(v_id) = version_id {
        conn.query_row(
            "SELECT content FROM versions WHERE id = ?1 AND page_id = ?2",
            rusqlite::params![v_id, page_id],
            |row| row.get(0)
        ).map_err(|e| format!("could not get version content: {e}"))?
    } else {
        conn.query_row(
            "SELECT content FROM pages WHERE id = ?1",
            rusqlite::params![page_id],
            |row| row.get(0)
        ).map_err(|e| format!("could not get page content: {e}"))?
    };
    
    Ok(content)
}

pub fn list_versions(app: &AppHandle, page_id: &str) -> Result<Vec<Version>, String> {
    validate_page_id(page_id)?;
    let conn = db::get_conn(app)?;
    
    let mut stmt = conn
        .prepare("SELECT id, page_id, created_at FROM versions WHERE page_id = ?1 ORDER BY created_at DESC")
        .map_err(|e| format!("could not prepare list versions: {e}"))?;

    let versions = stmt
        .query_map(rusqlite::params![page_id], |row| {
            Ok(Version {
                id: row.get(0)?,
                page_id: row.get(1)?,
                created_at: row.get(2)?,
            })
        })
        .map_err(|e| format!("could not query versions: {e}"))?
        .filter_map(Result::ok)
        .collect();

    Ok(versions)
}

pub fn restore_version(app: &AppHandle, page_id: &str, version_id: i64) -> Result<(), String> {
    validate_page_id(page_id)?;
    let mut conn = db::get_conn(app)?;
    let tx = conn.transaction().map_err(|e| format!("could not start transaction: {e}"))?;
    
    let content: String = tx.query_row(
        "SELECT content FROM versions WHERE id = ?1 AND page_id = ?2",
        rusqlite::params![version_id, page_id],
        |row| row.get(0)
    ).map_err(|e| format!("could not get version content: {e}"))?;
    
    let now = now_millis();
    
    tx.execute(
        "INSERT INTO versions (page_id, content, created_at) VALUES (?1, ?2, ?3)",
        rusqlite::params![page_id, content, now],
    ).map_err(|e| format!("could not save restored version record: {e}"))?;
    let new_version_id = tx.last_insert_rowid();
    
    tx.execute(
        "UPDATE pages SET current_version_id = ?1, updated_at = ?2, content = ?3 WHERE id = ?4",
        rusqlite::params![new_version_id, now, content, page_id],
    ).map_err(|e| format!("could not update page: {e}"))?;

    tx.commit().map_err(|e| format!("could not commit restore: {e}"))?;
    
    Ok(())
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Tag {
    pub id: i64,
    pub name: String,
}

pub fn add_tag(app: &AppHandle, page_id: &str, tag_name: &str) -> Result<(), String> {
    validate_page_id(page_id)?;
    let conn = db::get_conn(app)?;
    
    let tag_name_lower = tag_name.trim().to_lowercase();
    
    conn.execute(
        "INSERT OR IGNORE INTO tags (name) VALUES (?1)",
        rusqlite::params![tag_name_lower],
    ).map_err(|e| format!("could not insert tag: {e}"))?;
    
    let tag_id: i64 = conn.query_row(
        "SELECT id FROM tags WHERE name = ?1",
        rusqlite::params![tag_name_lower],
        |row| row.get(0)
    ).map_err(|e| format!("could not get tag id: {e}"))?;
    
    conn.execute(
        "INSERT OR IGNORE INTO page_tags (page_id, tag_id) VALUES (?1, ?2)",
        rusqlite::params![page_id, tag_id],
    ).map_err(|e| format!("could not link tag to page: {e}"))?;
    
    Ok(())
}

pub fn remove_tag(app: &AppHandle, page_id: &str, tag_name: &str) -> Result<(), String> {
    validate_page_id(page_id)?;
    let conn = db::get_conn(app)?;
    
    let tag_name_lower = tag_name.trim().to_lowercase();
    
    conn.execute(
        "DELETE FROM page_tags WHERE page_id = ?1 AND tag_id = (SELECT id FROM tags WHERE name = ?2)",
        rusqlite::params![page_id, tag_name_lower],
    ).map_err(|e| format!("could not remove tag: {e}"))?;
    
    Ok(())
}

pub fn list_tags_for_page(app: &AppHandle, page_id: &str) -> Result<Vec<Tag>, String> {
    validate_page_id(page_id)?;
    let conn = db::get_conn(app)?;
    
    let mut stmt = conn
        .prepare("SELECT t.id, t.name FROM tags t JOIN page_tags pt ON t.id = pt.tag_id WHERE pt.page_id = ?1 ORDER BY t.name")
        .map_err(|e| format!("could not prepare list tags: {e}"))?;

    let tags = stmt
        .query_map(rusqlite::params![page_id], |row| {
            Ok(Tag {
                id: row.get(0)?,
                name: row.get(1)?,
            })
        })
        .map_err(|e| format!("could not query tags: {e}"))?
        .filter_map(Result::ok)
        .collect();

    Ok(tags)
}

pub fn search_pages(app: &AppHandle, query: &str) -> Result<Vec<PageMeta>, String> {
    let conn = db::get_conn(app)?;
    let query_lower = format!("%{}%", query.to_lowercase());
    
    let mut stmt = conn
        .prepare("
            SELECT DISTINCT p.id, p.collection_id, p.title, p.created_at, p.updated_at 
            FROM pages p
            LEFT JOIN page_tags pt ON p.id = pt.page_id
            LEFT JOIN tags t ON pt.tag_id = t.id
            WHERE LOWER(p.title) LIKE ?1 OR LOWER(t.name) LIKE ?1
            ORDER BY p.updated_at DESC
        ")
        .map_err(|e| format!("could not prepare search pages: {e}"))?;

    let pages = stmt
        .query_map(rusqlite::params![query_lower], |row| {
            Ok(PageMeta {
                id: row.get(0)?,
                collection_id: row.get(1)?,
                title: row.get(2)?,
                created_at: row.get(3)?,
                updated_at: row.get(4)?,
            })
        })
        .map_err(|e| format!("could not query search results: {e}"))?
        .filter_map(Result::ok)
        .collect();

    Ok(pages)
}